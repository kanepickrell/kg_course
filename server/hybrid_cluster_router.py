@dataclass
class ClusterCard:
    """
    Structured, auditable description of a cluster.
    Compiled from graph data, not generated by an LLM.
    """
    cluster_id: str
    node_ids: Set[str]
    node_count: int
    type_distribution: Dict[str, int]
    primary_type: str
    team_distribution: Dict[str, int]
    primary_team: str
    mitre_techniques: Set[str]
    tools: Set[str]
    internal_edge_count: int
    external_edge_count: int
    edge_type_distribution: Dict[str, int]
    exemplar_paths: List[Dict[str, Any]]
    core_node_ids: List[str]
    core_node_labels: List[str]
    keywords: Set[str]
    centroid_embedding: Optional[np.ndarray] = None
    coherence_score: float = 0.0
    connectivity_score: float = 0.0
    created_at: str = ""
    updated_at: str = ""
    
    def to_summary_text(self) -> str:
        """Generate human-readable summary from card data"""
        type_str = ", ".join(f"{v} {k}" for k, v in 
                            sorted(self.type_distribution.items(), key=lambda x: -x[1])[:3])
        mitre_str = ", ".join(list(self.mitre_techniques)[:5]) if self.mitre_techniques else "none"
        tools_str = ", ".join(list(self.tools)[:5]) if self.tools else "none"
        
        return (
            f"[{self.primary_team.upper()}] {self.node_count} artifacts ({type_str}). "
            f"MITRE: {mitre_str}. Tools: {tools_str}. "
            f"Core: {', '.join(self.core_node_labels[:3])}."
        )
    
    def to_dict(self) -> Dict[str, Any]:
        """Serialize for API response"""
        return {
            "cluster_id": self.cluster_id,
            "node_count": self.node_count,
            "node_ids": list(self.node_ids)[:50],
            "type_distribution": self.type_distribution,
            "primary_type": self.primary_type,
            "team_distribution": self.team_distribution,
            "primary_team": self.primary_team,
            "mitre_techniques": list(self.mitre_techniques),
            "tools": list(self.tools),
            "internal_edges": self.internal_edge_count,
            "external_edges": self.external_edge_count,
            "edge_types": self.edge_type_distribution,
            "exemplar_paths": self.exemplar_paths,
            "core_nodes": self.core_node_labels[:5],
            "keywords": list(self.keywords)[:15],
            "coherence_score": self.coherence_score,
            "connectivity_score": self.connectivity_score,
            "summary": self.to_summary_text(),
            "created_at": self.created_at,
            "updated_at": self.updated_at,
        }
    
    def to_storage_dict(self) -> Dict[str, Any]:
        """Serialize for ArangoDB storage (no numpy arrays)"""
        d = self.to_dict()
        d["node_ids"] = list(self.node_ids)  # Full list for storage
        # Don't store embedding in JSON - too large
        return d


