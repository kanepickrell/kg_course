def create_hybrid_router_endpoints(app, router: HybridClusterRouter):
    """Add hybrid router endpoints to FastAPI"""
    from fastapi import Query, HTTPException
    from pydantic import BaseModel
    
    class ClusterConfig(BaseModel):
        semantic_weight: Optional[float] = None
        edge_weight: Optional[float] = None
        type_bonus: Optional[float] = None
        team_bonus: Optional[float] = None
        merge_threshold: Optional[float] = None
        min_cluster_size: Optional[int] = None
        max_cluster_size: Optional[int] = None
    
    @app.get("/api/neural-v3/health")
    def neural_v3_health():
        return {
            "status": "ok",
            "version": "3.1-hybrid-persistent",
            "initialized": router._initialized,
            "method": router.clustering_method,
            "agents": len(router.agents),
            "nodes": len(router.nodes),
            "edges": len(router.edges),
        }
    
    @app.post("/api/neural-v3/initialize")
    def neural_v3_initialize(
        force: bool = False, 
        method: str = "hybrid",
        use_cached: bool = True
    ):
        success = router.initialize(force_reload=force, method=method, use_cached=use_cached)
        return {"success": success, "stats": router.get_stats()}
    
    @app.post("/api/neural-v3/recluster")
    def neural_v3_recluster(config: Optional[ClusterConfig] = None):
        """Force re-clustering with optional config changes"""
        cfg = config.dict(exclude_none=True) if config else None
        return router.recluster(cfg)
    
