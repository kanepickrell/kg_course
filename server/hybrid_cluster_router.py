class OllamaClient:
    """Client for Ollama embeddings and generation"""
    
    def __init__(self, host: str = OLLAMA_HOST):
        self.host = host.rstrip('/')
        self.embedding_cache: Dict[str, np.ndarray] = {}
        self._healthy = None
    
    def health_check(self) -> bool:
        if self._healthy is not None:
            return self._healthy
        try:
            response = requests.get(f"{self.host}/api/tags", timeout=5)
            self._healthy = response.status_code == 200
            return self._healthy
        except:
            self._healthy = False
            return False
    
    def get_embedding(self, text: str, model: str = EMBEDDING_MODEL) -> Optional[np.ndarray]:
        cache_key = hashlib.md5(f"{model}:{text[:500]}".encode()).hexdigest()
        if cache_key in self.embedding_cache:
            return self.embedding_cache[cache_key]
        
        try:
            response = requests.post(
                f"{self.host}/api/embeddings",
                json={"model": model, "prompt": text[:1000]},
                timeout=30
            )
            if response.status_code == 200:
                data = response.json()
                if "embedding" in data:
                    embedding = np.array(data["embedding"])
                elif "embeddings" in data:
                    embedding = np.array(data["embeddings"][0])
                else:
                    return None
                self.embedding_cache[cache_key] = embedding
                return embedding
        except Exception as e:
            print(f"⚠️ Embedding error: {e}")
        return None
    
    def generate_context(self, cluster_card: ClusterCard, query: str, model: str = SLM_MODEL) -> Optional[str]:
        """Generate context using ClusterCard data (grounded, not improvised)"""
        card_facts = (
            f"Cluster contains {cluster_card.node_count} artifacts, "
            f"primarily {cluster_card.primary_type}s owned by {cluster_card.primary_team}.\n"
            f"MITRE techniques: {', '.join(list(cluster_card.mitre_techniques)[:5]) or 'none'}.\n"
            f"Tools: {', '.join(list(cluster_card.tools)[:5]) or 'none'}.\n"
            f"Core artifacts: {', '.join(cluster_card.core_node_labels[:3])}."
        )
        
        prompt = f"""Given these FACTS about a knowledge cluster:
{card_facts}

Query: {query}

Based ONLY on the facts above, write ONE sentence (max 25 words) explaining how this cluster helps answer the query.
If the facts don't relate to the query, respond with exactly: NOT_RELEVANT"""

        try:
            response = requests.post(
                f"{self.host}/api/generate",
                json={
                    "model": model,
                    "prompt": prompt,
                    "stream": False,
                    "options": {"num_predict": 60, "temperature": 0.2}
                },
                timeout=60
            )
            if response.status_code == 200:
                text = response.json().get("response", "").strip()
                if "NOT_RELEVANT" in text.upper():
                    return None
                return text
        except Exception as e:
            print(f"⚠️ Generation error: {e}")
        return None


