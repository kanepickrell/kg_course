class HybridClusterer:
    """
    Clusters nodes using semantic similarity + structural affinity.
    
    Improvements:
    - Uses actual edge weights from PROPAGATION_WEIGHTS
    - Configurable parameters
    - Caches embeddings for incremental updates
    """
    
    def __init__(self, ollama: OllamaClient, config: Optional[Dict[str, Any]] = None):
        self.ollama = ollama
        self.config = {**DEFAULT_CLUSTERING_CONFIG, **(config or {})}
        self.embedding_cache: Dict[str, np.ndarray] = {}
    
    def cluster(
        self,
        nodes: Dict[str, GraphNode],
        edges: List[GraphEdge],
        existing_assignments: Optional[Dict[str, str]] = None
    ) -> Tuple[Dict[str, str], Dict[str, np.ndarray]]:
        """
        Cluster nodes and return (node_id -> cluster_id, embeddings dict).
        
        If existing_assignments provided, only re-cluster nodes that are new
        or whose neighbors have changed significantly.
        """
        if not nodes:
            return {}, {}
        
        node_ids = list(nodes.keys())
        n = len(node_ids)
        
        print(f"🔬 Hybrid clustering {n} nodes...")
        print(f"   Config: semantic={self.config['semantic_weight']}, "
              f"edge={self.config['edge_weight']}, threshold={self.config['merge_threshold']}")
        
        # Build edge lookup with proper weights
        edge_set: Set[Tuple[str, str]] = set()
        edge_weights: Dict[Tuple[str, str], float] = {}
        
        for edge in edges:
            # Use PROPAGATION_WEIGHTS for the edge type
            weight = PROPAGATION_WEIGHTS.get(edge.edge_type, 0.5)
            pair = (edge.source, edge.target)
            pair_rev = (edge.target, edge.source)
            edge_set.add(pair)
            edge_set.add(pair_rev)
            # Take max weight if multiple edges exist
            edge_weights[pair] = max(edge_weights.get(pair, 0), weight)
            edge_weights[pair_rev] = max(edge_weights.get(pair_rev, 0), weight)
        
        # Compute embeddings
        print("   Computing embeddings...")
        embeddings: Dict[str, np.ndarray] = {}
        
        for node_id, node in nodes.items():
            # Check cache first
            if node_id in self.embedding_cache:
                embeddings[node_id] = self.embedding_cache[node_id]
                continue
            
            text = f"{node.label} {node.node_type} {node.description}"
            if node.tags:
                text += " " + " ".join(node.tags)
            
            emb = self.ollama.get_embedding(text[:500])
            if emb is not None:
                embeddings[node_id] = emb
                self.embedding_cache[node_id] = emb
        
        if len(embeddings) < 2:
            print("   ⚠️ Not enough embeddings, falling back to team-based clustering")
            return self._fallback_team_clustering(nodes), embeddings
        
        # Build affinity matrix
        print("   Building affinity matrix...")
        affinity = np.zeros((n, n))
        
        id_to_idx = {nid: i for i, nid in enumerate(node_ids)}
        
        for i, id_i in enumerate(node_ids):
            for j, id_j in enumerate(node_ids):
                if i == j:
                    affinity[i, j] = 1.0
                    continue
                
                score = 0.0
                
                # Semantic similarity (cosine)
                if id_i in embeddings and id_j in embeddings:
                    emb_i = embeddings[id_i]
                    emb_j = embeddings[id_j]
                    cos_sim = np.dot(emb_i, emb_j) / (np.linalg.norm(emb_i) * np.linalg.norm(emb_j) + 1e-9)
                    score += self.config["semantic_weight"] * max(0, cos_sim)
                
                # Edge existence bonus (using actual edge weight)
                if (id_i, id_j) in edge_set:
                    edge_w = edge_weights.get((id_i, id_j), 0.5)
                    score += self.config["edge_weight"] * edge_w
                
                # Type match bonus
                if nodes[id_i].node_type == nodes[id_j].node_type:
                    score += self.config["type_bonus"]
                
                # Team match bonus
                if nodes[id_i].team_cluster == nodes[id_j].team_cluster:
                    score += self.config["team_bonus"]
                
                affinity[i, j] = score
        
        # Agglomerative clustering
        print("   Running agglomerative clustering...")
        clusters = self._agglomerative_cluster(affinity, node_ids, nodes)
        
        # Stats
        cluster_counts = defaultdict(int)
        for cid in clusters.values():
            cluster_counts[cid] += 1
        
        print(f"   ✓ Created {len(set(clusters.values()))} clusters")
        sizes = sorted(cluster_counts.values(), reverse=True)
        print(f"   Sizes: {sizes[:10]}{'...' if len(sizes) > 10 else ''}")
        
        return clusters, embeddings
    
    def _agglomerative_cluster(
        self,
        affinity: np.ndarray,
        node_ids: List[str],
        nodes: Dict[str, GraphNode]
    ) -> Dict[str, str]:
        """Agglomerative clustering with configurable parameters"""
        n = len(node_ids)
        threshold = self.config["merge_threshold"]
        max_size = self.config["max_cluster_size"]
        
        cluster_assignments = {node_id: i for i, node_id in enumerate(node_ids)}
        cluster_members: Dict[int, Set[int]] = {i: {i} for i in range(n)}
        
        while True:
            best_merge = None
            best_score = threshold
            
            cluster_ids = list(cluster_members.keys())
            
            for ci in cluster_ids:
                if ci not in cluster_members:
                    continue
                if len(cluster_members[ci]) >= max_size:
                    continue
                
                for cj in cluster_ids:
                    if cj not in cluster_members or ci >= cj:
                        continue
                    if len(cluster_members[cj]) >= max_size:
                        continue
                    if len(cluster_members[ci]) + len(cluster_members[cj]) > max_size:
                        continue
                    
                    # Average linkage
                    total = sum(affinity[mi, mj] 
                               for mi in cluster_members[ci] 
                               for mj in cluster_members[cj])
                    count = len(cluster_members[ci]) * len(cluster_members[cj])
                    avg = total / count if count > 0 else 0
                    
                    if avg > best_score:
                        best_score = avg
                        best_merge = (ci, cj)
            
            if best_merge is None:
                break
            
            ci, cj = best_merge
            cluster_members[ci] = cluster_members[ci] | cluster_members[cj]
            del cluster_members[cj]
            
            for idx in cluster_members[ci]:
                cluster_assignments[node_ids[idx]] = ci
        
        # Normalize cluster IDs
        unique = sorted(set(cluster_assignments.values()))
        cluster_map = {old: f"cluster_{i}" for i, old in enumerate(unique)}
        
        return {nid: cluster_map[cid] for nid, cid in cluster_assignments.items()}
    
    def _fallback_team_clustering(self, nodes: Dict[str, GraphNode]) -> Dict[str, str]:
        """Fallback: cluster by team ownership"""
        return {nid: f"cluster_{node.team_cluster}" for nid, node in nodes.items()}


