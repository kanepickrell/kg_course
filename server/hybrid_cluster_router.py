def extract_mitre_ids(text: str) -> Set[str]:
    """Extract MITRE ATT&CK technique IDs"""
    matches = MITRE_PATTERN.findall(text)
    return {m.upper() for m in matches}


def extract_tools(text: str) -> Set[str]:
    """Extract known tool names"""
    text_lower = text.lower()
    return {entity for entity in KNOWN_ENTITIES if entity in text_lower}


def extract_keywords(text: str) -> Set[str]:
    """Extract meaningful keywords"""
    stop_words = {'the', 'a', 'an', 'is', 'are', 'was', 'were', 'be', 'been',
                  'being', 'have', 'has', 'had', 'do', 'does', 'did', 'will',
                  'would', 'could', 'should', 'may', 'might', 'must', 'shall',
                  'can', 'need', 'to', 'of', 'in', 'for', 'on', 'with', 'at',
                  'by', 'from', 'as', 'into', 'through', 'during', 'before',
                  'after', 'above', 'below', 'and', 'but', 'or', 'nor', 'so',
                  'yet', 'both', 'either', 'neither', 'not', 'only', 'own',
                  'same', 'than', 'too', 'very', 'just', 'this', 'that', 'it'}
    
    words = re.findall(r'\b[a-zA-Z_][a-zA-Z0-9_]*\b', text.lower())
    return {w for w in words if len(w) > 2 and w not in stop_words}


