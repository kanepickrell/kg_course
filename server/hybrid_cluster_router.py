class HybridClusterRouter:
    """
    Neural graph router using hybrid semantic-structural clustering.
    
    Improvements:
    - Persistence of cluster assignments
    - Incremental update support
    - Configurable clustering parameters
    """
    
    def __init__(self, ollama_client: Optional[OllamaClient] = None):
        self.ollama = ollama_client or OllamaClient()
        
        # ArangoDB connection
        self.client = ArangoClient(hosts=ARANGO_HOST)
        self.db = self.client.db(ARANGO_DB, username=ARANGO_USER, password=ARANGO_PASSWORD)
        
        # Persistence
        self.persistence = ClusterPersistence(self.db)
        
        # Data structures
        self.nodes: Dict[str, GraphNode] = {}
        self.edges: List[GraphEdge] = []
        self.agents: Dict[str, ClusterAgent] = {}
        self.node_to_agent: Dict[str, str] = {}
        self.agent_adjacency: Dict[str, Set[str]] = defaultdict(set)
        self.embeddings: Dict[str, np.ndarray] = {}
        
        self.available_edge_collections: List[str] = []
        self.clustering_method = "hybrid"
        self.clustering_config = DEFAULT_CLUSTERING_CONFIG.copy()
        
        self._initialized = False
    
    def initialize(
        self, 
        force_reload: bool = False, 
        method: str = "hybrid",
        use_cached: bool = True,
        config: Optional[Dict[str, Any]] = None
    ) -> bool:
        """
        Initialize the router.
        
        Args:
            force_reload: If True, re-cluster even if cached assignments exist
            method: "hybrid" or "label_propagation"
            use_cached: If True, try to load cached cluster assignments
            config: Override clustering parameters
        """
        if self._initialized and not force_reload:
            return True
        
        self.clustering_method = method
        if config:
            self.clustering_config.update(config)
        
        print("\n" + "="*60)
        print(f"HYBRID CLUSTER ROUTER v2 - INITIALIZATION")
        print(f"Method: {method}, Force: {force_reload}, Cached: {use_cached}")
        print("="*60)
        
        # Check Ollama
        if self.ollama.health_check():
            print(f"✓ Ollama connected at {OLLAMA_HOST}")
        else:
            print("⚠️ Ollama not available - limited functionality")
        
        # Load graph data
        self._validate_edge_collections()
        self._load_nodes()
        
        if not self.nodes:
            print("⚠️ No data nodes found")
            self._initialized = True
            return True
        
        self._load_edges()
        
        # Try to use cached assignments
        cached_assignments = None
        if use_cached and not force_reload:
            cached_assignments = self.persistence.load_assignments()
            
            if cached_assignments:
                # Validate cache: check if all current nodes have assignments
                current_nodes = set(self.nodes.keys())
                cached_nodes = set(cached_assignments.keys())
                
                missing = current_nodes - cached_nodes
                if missing:
                    print(f"⚠️ {len(missing)} new nodes since last clustering, re-clustering...")
                    cached_assignments = None
                else:
                    # Remove assignments for deleted nodes
                    cached_assignments = {k: v for k, v in cached_assignments.items() 
                                         if k in current_nodes}
        
        # Cluster (or use cache)
        if cached_assignments:
            print("📂 Using cached cluster assignments")
            self._create_agents_from_assignments(cached_assignments)
        else:
            if method == "hybrid":
                self._create_agents_hybrid()
            else:
                self._create_agents_label_propagation()
            
            # Save for next time
            assignments = {nid: aid for nid, aid in self.node_to_agent.items()}
            self.persistence.save_assignments(assignments, method)
        
        # Build agent adjacency
        self._build_agent_adjacency()
        
        self._initialized = True
        
        print(f"\n✅ Router initialized")
        print(f"   Nodes: {len(self.nodes)}")
        print(f"   Edges: {len(self.edges)}")
        print(f"   Agents: {len(self.agents)}")
        
        return True
    
    def _validate_edge_collections(self):
        """Check which edge collections exist"""
        all_colls = [c['name'] for c in self.db.collections() if not c['name'].startswith('_')]
        self.available_edge_collections = [ec for ec in EDGE_COLLECTIONS if ec in all_colls]
        print(f"✓ Found {len(self.available_edge_collections)} edge collections")
    
    def _load_nodes(self):
        """Load all data nodes"""
        all_colls = [c['name'] for c in self.db.collections() if not c['name'].startswith('_')]
        data_colls = [c for c in all_colls 
                      if c not in SCHEMA_COLLECTIONS and c not in EDGE_COLLECTIONS]
        
        print(f"📊 Loading nodes from {len(data_colls)} collections...")
        
        self.nodes.clear()
        for coll_name in data_colls:
            try:
                for doc in self.db.aql.execute(f"FOR d IN `{coll_name}` RETURN d"):
                    tags = doc.get("tags", [])
                    if isinstance(tags, str):
                        tags = [tags]
                    
                    self.nodes[doc["_id"]] = GraphNode(
                        id=doc["_id"],
                        label=doc.get("name", doc.get("label", doc.get("_key", ""))),
                        node_type=doc.get("type", "unknown"),
                        team_cluster=doc.get("cluster", "unknown"),
                        description=doc.get("description", ""),
                        tags=tags,
                        properties={k: v for k, v in doc.items() if k not in ['_id', '_key', '_rev']}
                    )
            except Exception as e:
                print(f"⚠️ Error loading {coll_name}: {e}")
        
        print(f"✓ Loaded {len(self.nodes)} nodes")
    
    def _load_edges(self):
        """Load all edges"""
        node_ids = set(self.nodes.keys())
        self.edges.clear()
        
        for edge_coll in self.available_edge_collections:
            try:
                for e in self.db.aql.execute(f"FOR e IN `{edge_coll}` RETURN e"):
                    if e["_from"] in node_ids and e["_to"] in node_ids:
                        self.edges.append(GraphEdge(
                            id=e["_id"],
                            source=e["_from"],
                            target=e["_to"],
                            edge_type=edge_coll,
                            weight=PROPAGATION_WEIGHTS.get(edge_coll, 0.5)
                        ))
            except Exception as e:
                print(f"⚠️ Error loading {edge_coll}: {e}")
        
        print(f"✓ Loaded {len(self.edges)} edges")
    
    def _create_agents_hybrid(self):
        """Create agents using hybrid clustering"""
        clusterer = HybridClusterer(self.ollama, self.clustering_config)
        cluster_assignments, self.embeddings = clusterer.cluster(self.nodes, self.edges)
        
        self._create_agents_from_assignments(cluster_assignments)
    
    def _create_agents_from_assignments(self, assignments: Dict[str, str]):
        """Create agents from pre-computed assignments"""
        # Group by cluster
        cluster_nodes: Dict[str, Set[str]] = defaultdict(set)
        for node_id, cluster_id in assignments.items():
            cluster_nodes[cluster_id].add(node_id)
        
        # Compile cards and create agents
        compiler = ClusterCardCompiler(self.ollama)
        min_size = self.clustering_config["min_cluster_size"]
        
        print(f"🃏 Compiling ClusterCards...")
        
        self.agents.clear()
        self.node_to_agent.clear()
        
        for cluster_id, node_ids in cluster_nodes.items():
            if len(node_ids) < min_size:
                continue
            
            card = compiler.compile(
                cluster_id=cluster_id,
                node_ids=node_ids,
                nodes=self.nodes,
                edges=self.edges,
                all_clusters=assignments,
                embeddings=self.embeddings
            )
            
            agent = ClusterAgent(agent_id=f"agent_{cluster_id}", card=card)
            self.agents[agent.agent_id] = agent
            
            for nid in node_ids:
                self.node_to_agent[nid] = agent.agent_id
        
        print(f"✓ Created {len(self.agents)} agents with ClusterCards")
    
    def _create_agents_label_propagation(self):
        """Label propagation clustering (for comparison)"""
        adjacency: Dict[str, Set[str]] = defaultdict(set)
        for edge in self.edges:
            adjacency[edge.source].add(edge.target)
            adjacency[edge.target].add(edge.source)
        
        communities = {nid: nid for nid in self.nodes}
        
        for _ in range(15):
            changed = False
            node_ids = list(communities.keys())
            np.random.shuffle(node_ids)
            
            for nid in node_ids:
                neighbors = adjacency.get(nid, set())
                if not neighbors:
                    continue
                
                label_counts: Dict[str, int] = defaultdict(int)
                for neighbor in neighbors:
                    label_counts[communities[neighbor]] += 1
                
                if label_counts:
                    best = max(label_counts, key=label_counts.get)
                    if communities[nid] != best:
                        communities[nid] = best
                        changed = True
            
            if not changed:
                break
        
        unique = list(set(communities.values()))
        cmap = {old: f"cluster_{i}" for i, old in enumerate(unique)}
        assignments = {nid: cmap[cid] for nid, cid in communities.items()}
        
        self._create_agents_from_assignments(assignments)
    
    def _build_agent_adjacency(self):
        """Build agent adjacency from inter-cluster edges"""
        self.agent_adjacency.clear()
        
        for edge in self.edges:
            src = self.node_to_agent.get(edge.source)
            tgt = self.node_to_agent.get(edge.target)
            if src and tgt and src != tgt:
                self.agent_adjacency[src].add(tgt)
                self.agent_adjacency[tgt].add(src)
    
    def search(self, query: str, top_k: int = 5) -> ActivationResult:
        """Execute neural search"""
        start = time.time()
        
        if not self._initialized:
            self.initialize()
        
        if not self.agents:
            return ActivationResult(
                query=query, entry_agents=[], entry_scores={},
                activated_agents=[], contributing_agents=[],
                propagation_path=[], contexts={}, cluster_cards={},
                nodes_traversed=0, total_time_ms=0
            )
        
        print(f"\n🔍 Search: '{query[:60]}...'")
        
        # Extract query features
        query_mitre = extract_mitre_ids(query)
        query_tools = extract_tools(query)
        query_keywords = extract_keywords(query)
        query_emb = self.ollama.get_embedding(query) if self.ollama.health_check() else None
        
        # Score agents
        agent_scores: Dict[str, Dict[str, float]] = {}
        for aid, agent in self.agents.items():
            agent_scores[aid] = self._compute_agent_score(
                agent, query_emb, query_mitre, query_tools, query_keywords
            )
        
        # Select entry agents
        sorted_agents = sorted(agent_scores.items(), key=lambda x: x[1]["combined"], reverse=True)
        entry_agents = [aid for aid, s in sorted_agents[:top_k] 
                       if s["combined"] >= ACTIVATION_THRESHOLD or len([a for a in sorted_agents[:top_k] if a[1]["combined"] >= ACTIVATION_THRESHOLD]) < 2][:top_k]
        
        print(f"   Entry: {entry_agents}")
        
        # Propagation (BFS)
        activated = set(entry_agents)
        signals = {aid: agent_scores[aid]["combined"] for aid in entry_agents}
        prop_path = []
        
        queue = [(aid, 0, signals[aid]) for aid in entry_agents]
        visited = {aid: 0 for aid in entry_agents}
        
        while queue and len(activated) < MAX_ACTIVE_AGENTS:
            current, depth, signal = queue.pop(0)
            if depth >= MAX_HOPS:
                continue
            
            for neighbor in self.agent_adjacency.get(current, set()):
                if neighbor in visited and visited[neighbor] <= depth:
                    continue
                
                prop_sig = signal * SIGNAL_DECAY
                if prop_sig >= ACTIVATION_THRESHOLD:
                    activated.add(neighbor)
                    visited[neighbor] = depth + 1
                    signals[neighbor] = prop_sig
                    prop_path.append({
                        "from_agent": current, "to_agent": neighbor,
                        "signal": prop_sig, "hop": depth + 1
                    })
                    queue.append((neighbor, depth + 1, prop_sig))
        
        print(f"   Activated: {len(activated)}, Propagation: {len(prop_path)} hops")
        
        # Generate contexts
        contexts = {}
        contributing = []
        cluster_cards = {}
        
        for aid in sorted(activated, key=lambda a: signals.get(a, 0), reverse=True)[:10]:
            agent = self.agents[aid]
            agent.activation_count += 1
            cluster_cards[aid] = agent.card.to_dict()
            
            if self.ollama.health_check():
                ctx = self.ollama.generate_context(agent.card, query)
                if ctx:
                    contexts[aid] = ctx
                    contributing.append(aid)
            else:
                contexts[aid] = agent.card.to_summary_text()
                contributing.append(aid)
        
        elapsed = (time.time() - start) * 1000
        
        return ActivationResult(
            query=query,
            entry_agents=entry_agents,
            entry_scores={aid: agent_scores[aid] for aid in entry_agents},
            activated_agents=list(activated),
            contributing_agents=contributing,
            propagation_path=prop_path,
            contexts=contexts,
            cluster_cards=cluster_cards,
            nodes_traversed=len(self.nodes),
            total_time_ms=elapsed
        )
    
    def _compute_agent_score(
        self, agent: ClusterAgent,
        query_emb: Optional[np.ndarray],
        query_mitre: Set[str],
        query_tools: Set[str],
        query_keywords: Set[str]
    ) -> Dict[str, float]:
        """Compute relevance score for an agent"""
        card = agent.card
        scores = {"semantic": 0.0, "mitre": 0.0, "tools": 0.0, "keywords": 0.0}
        
        if query_emb is not None and card.centroid_embedding is not None:
            dot = np.dot(query_emb, card.centroid_embedding)
            norm = np.linalg.norm(query_emb) * np.linalg.norm(card.centroid_embedding)
            scores["semantic"] = float(dot / norm) if norm > 0 else 0.0
        
        if query_mitre and card.mitre_techniques:
            scores["mitre"] = len(query_mitre & card.mitre_techniques) / len(query_mitre)
        
        if query_tools and card.tools:
            scores["tools"] = len(query_tools & card.tools) / len(query_tools)
        
        if query_keywords and card.keywords:
            scores["keywords"] = len(query_keywords & card.keywords) / len(query_keywords | card.keywords)
        
        scores["combined"] = (
            0.4 * scores["semantic"] +
            0.25 * scores["mitre"] +
            0.25 * scores["tools"] +
            0.1 * scores["keywords"]
        )
        return scores
    
    # === API Methods ===
    
    def get_stats(self) -> Dict[str, Any]:
        """Get router statistics"""
        return {
            "initialized": self._initialized,
            "clustering_method": self.clustering_method,
            "clustering_config": self.clustering_config,
            "total_nodes": len(self.nodes),
            "total_edges": len(self.edges),
            "total_agents": len(self.agents),
            "edge_collections": self.available_edge_collections,
            "persistence_info": self.persistence.get_assignment_metadata(),
            "agent_stats": {
                aid: {
                    "nodes": agent.card.node_count,
                    "primary_type": agent.card.primary_type,
                    "primary_team": agent.card.primary_team,
                    "mitre": " ".join(list(agent.card.mitre_techniques)[:5]),
                    "tools": " ".join(list(agent.card.tools)[:5]),
                    "coherence": agent.card.coherence_score,
                    "connectivity": agent.card.connectivity_score,
                    "activations": agent.activation_count,
                }
                for aid, agent in self.agents.items()
            }
        }
    
    def get_agent_info(self, agent_id: str) -> Optional[Dict[str, Any]]:
        """Get detailed agent info"""
        agent = self.agents.get(agent_id)
        if not agent:
            return None
        return {
            "agent_id": agent.agent_id,
            **agent.card.to_dict(),
            "activation_count": agent.activation_count,
            "neighbors": list(self.agent_adjacency.get(agent_id, set()))
        }
    
    def get_all_agents(self) -> List[Dict[str, Any]]:
        """Get all agents summary"""
        return [
            {
                "agent_id": a.agent_id,
                "cluster_id": a.card.cluster_id,
                "node_count": a.card.node_count,
                "primary_type": a.card.primary_type,
                "primary_team": a.card.primary_team,
                "mitre": list(a.card.mitre_techniques)[:3],
                "tools": list(a.card.tools)[:3],
                "coherence": round(a.card.coherence_score, 2),
                "activation_count": a.activation_count,
            }
            for a in self.agents.values()
        ]
    
    def recluster(self, config: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Force re-clustering with optional new config"""
        if config:
            self.clustering_config.update(config)
        
        self.initialize(force_reload=True, method=self.clustering_method, 
                       use_cached=False, config=self.clustering_config)
        
        return self.get_stats()


