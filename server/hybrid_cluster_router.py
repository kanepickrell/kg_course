class ClusterCardCompiler:
    """
    Compiles ClusterCards from graph data.
    
    Improvements:
    - Coherence uses embedding similarity
    - Timestamps for tracking updates
    """
    
    def __init__(self, ollama: OllamaClient):
        self.ollama = ollama
    
    def compile(
        self,
        cluster_id: str,
        node_ids: Set[str],
        nodes: Dict[str, GraphNode],
        edges: List[GraphEdge],
        all_clusters: Dict[str, str],
        embeddings: Optional[Dict[str, np.ndarray]] = None
    ) -> ClusterCard:
        """Compile a ClusterCard for a cluster"""
        
        cluster_nodes = [nodes[nid] for nid in node_ids if nid in nodes]
        now = datetime.utcnow().isoformat()
        
        # Type distribution
        type_dist: Dict[str, int] = defaultdict(int)
        for node in cluster_nodes:
            type_dist[node.node_type] += 1
        primary_type = max(type_dist.keys(), key=lambda k: type_dist[k]) if type_dist else "unknown"
        
        # Team distribution
        team_dist: Dict[str, int] = defaultdict(int)
        for node in cluster_nodes:
            team_dist[node.team_cluster] += 1
        primary_team = max(team_dist.keys(), key=lambda k: team_dist[k]) if team_dist else "unknown"
        
        # Extract entities
        all_mitre: Set[str] = set()
        all_tools: Set[str] = set()
        all_keywords: Set[str] = set()
        
        for node in cluster_nodes:
            for text in [node.label, node.description] + node.tags:
                all_mitre.update(extract_mitre_ids(text))
                all_tools.update(extract_tools(text))
                all_keywords.update(extract_keywords(text))
        
        # Edge analysis
        internal_edges = 0
        external_edges = 0
        edge_type_dist: Dict[str, int] = defaultdict(int)
        
        for edge in edges:
            src_cluster = all_clusters.get(edge.source)
            tgt_cluster = all_clusters.get(edge.target)
            
            if src_cluster == cluster_id and tgt_cluster == cluster_id:
                internal_edges += 1
                edge_type_dist[edge.edge_type] += 1
            elif src_cluster == cluster_id or tgt_cluster == cluster_id:
                external_edges += 1
        
        # Core nodes
        node_degrees: Dict[str, int] = defaultdict(int)
        for edge in edges:
            if edge.source in node_ids and edge.target in node_ids:
                node_degrees[edge.source] += 1
                node_degrees[edge.target] += 1
        
        core_nodes = sorted(node_ids, key=lambda n: node_degrees.get(n, 0), reverse=True)[:5]
        core_labels = [nodes[n].label for n in core_nodes if n in nodes]
        
        # Exemplar paths
        exemplar_paths = self._find_exemplar_paths(node_ids, edges)
        
        # Centroid embedding
        centroid = None
        if self.ollama.health_check() and embeddings:
            cluster_embeddings = [embeddings[nid] for nid in node_ids if nid in embeddings]
            if cluster_embeddings:
                centroid = np.mean(cluster_embeddings, axis=0)
        
        # Coherence (improved: uses embeddings)
        coherence = self._compute_coherence(cluster_nodes, embeddings)
        
        # Connectivity
        max_internal = len(node_ids) * (len(node_ids) - 1) / 2
        connectivity = internal_edges / max_internal if max_internal > 0 else 0
        
        return ClusterCard(
            cluster_id=cluster_id,
            node_ids=node_ids,
            node_count=len(node_ids),
            type_distribution=dict(type_dist),
            primary_type=primary_type,
            team_distribution=dict(team_dist),
            primary_team=primary_team,
            mitre_techniques=all_mitre,
            tools=all_tools,
            internal_edge_count=internal_edges,
            external_edge_count=external_edges,
            edge_type_distribution=dict(edge_type_dist),
            exemplar_paths=exemplar_paths,
            core_node_ids=core_nodes,
            core_node_labels=core_labels,
            keywords=all_keywords,
            centroid_embedding=centroid,
            coherence_score=coherence,
            connectivity_score=connectivity,
            created_at=now,
            updated_at=now,
        )
    
    def _find_exemplar_paths(self, node_ids: Set[str], edges: List[GraphEdge]) -> List[Dict[str, Any]]:
        """Find common 2-hop patterns within cluster"""
        adj: Dict[str, List[Tuple[str, str]]] = defaultdict(list)
        for edge in edges:
            if edge.source in node_ids and edge.target in node_ids:
                adj[edge.source].append((edge.target, edge.edge_type))
        
        patterns: Dict[str, int] = defaultdict(int)
        for src in adj:
            for mid, e1 in adj[src]:
                for tgt, e2 in adj.get(mid, []):
                    if tgt != src:
                        patterns[f"{e1}->{e2}"] += 1
        
        sorted_patterns = sorted(patterns.items(), key=lambda x: -x[1])[:5]
        return [{"pattern": p, "count": c} for p, c in sorted_patterns]
    
    def _compute_coherence(
        self, 
        nodes: List[GraphNode], 
        embeddings: Optional[Dict[str, np.ndarray]] = None
    ) -> float:
        """
        Compute semantic coherence using:
        1. Type homogeneity (30%)
        2. Team homogeneity (30%)
        3. Embedding similarity (40%)
        """
        if len(nodes) < 2:
            return 1.0
        
        # Type homogeneity
        types = [n.node_type for n in nodes]
        type_homo = max(types.count(t) for t in set(types)) / len(types)
        
        # Team homogeneity
        teams = [n.team_cluster for n in nodes]
        team_homo = max(teams.count(t) for t in set(teams)) / len(teams)
        
        # Embedding coherence
        emb_coherence = 0.5  # Default
        if embeddings:
            node_ids = [n.id for n in nodes if n.id in embeddings]
            if len(node_ids) >= 2:
                # Sample for efficiency (max 15 nodes)
                sample = node_ids[:15]
                sims = []
                for i, id_i in enumerate(sample):
                    for id_j in sample[i+1:]:
                        emb_i, emb_j = embeddings[id_i], embeddings[id_j]
                        sim = np.dot(emb_i, emb_j) / (np.linalg.norm(emb_i) * np.linalg.norm(emb_j) + 1e-9)
                        sims.append(max(0, sim))
                if sims:
                    emb_coherence = np.mean(sims)
        
        return 0.3 * type_homo + 0.3 * team_homo + 0.4 * emb_coherence


