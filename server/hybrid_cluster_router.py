class ClusterPersistence:
    """
    Persists cluster assignments and cards to ArangoDB.
    Enables incremental updates without full re-clustering.
    """
    
    ASSIGNMENTS_COLLECTION = "cluster_assignments"
    CARDS_COLLECTION = "cluster_cards"
    
    def __init__(self, db):
        self.db = db
        self._ensure_collections()
    
    def _ensure_collections(self):
        """Create persistence collections if they don't exist"""
        for coll_name in [self.ASSIGNMENTS_COLLECTION, self.CARDS_COLLECTION]:
            if not self.db.has_collection(coll_name):
                self.db.create_collection(coll_name)
                print(f"✓ Created collection: {coll_name}")
    
    def save_assignments(self, assignments: Dict[str, str], method: str = "hybrid"):
        """Save node -> cluster assignments"""
        coll = self.db.collection(self.ASSIGNMENTS_COLLECTION)
        
        # Clear existing
        coll.truncate()
        
        # Save as single document with all assignments
        doc = {
            "_key": "current",
            "method": method,
            "assignments": assignments,
            "node_count": len(assignments),
            "cluster_count": len(set(assignments.values())),
            "updated_at": datetime.utcnow().isoformat(),
        }
        coll.insert(doc, overwrite=True)
        print(f"✓ Saved {len(assignments)} cluster assignments")
    
    def load_assignments(self) -> Optional[Dict[str, str]]:
        """Load saved cluster assignments"""
        coll = self.db.collection(self.ASSIGNMENTS_COLLECTION)
        try:
            doc = coll.get("current")
            if doc:
                print(f"✓ Loaded {doc['node_count']} cluster assignments ({doc['method']})")
                return doc["assignments"]
        except:
            pass
        return None
    
    def save_cards(self, cards: Dict[str, ClusterCard]):
        """Save cluster cards"""
        coll = self.db.collection(self.CARDS_COLLECTION)
        coll.truncate()
        
        for cluster_id, card in cards.items():
            doc = card.to_storage_dict()
            doc["_key"] = cluster_id.replace("/", "_")
            coll.insert(doc, overwrite=True)
        
        print(f"✓ Saved {len(cards)} cluster cards")
    
    def load_cards(self) -> Dict[str, Dict[str, Any]]:
        """Load saved cluster cards (as dicts, not ClusterCard objects)"""
        coll = self.db.collection(self.CARDS_COLLECTION)
        cards = {}
        for doc in coll.all():
            cluster_id = doc.get("cluster_id", doc["_key"])
            cards[cluster_id] = doc
        if cards:
            print(f"✓ Loaded {len(cards)} cluster cards")
        return cards
    
    def get_assignment_metadata(self) -> Optional[Dict[str, Any]]:
        """Get metadata about current assignments without loading all data"""
        coll = self.db.collection(self.ASSIGNMENTS_COLLECTION)
        try:
            doc = coll.get("current")
            if doc:
                return {
                    "method": doc.get("method"),
                    "node_count": doc.get("node_count"),
                    "cluster_count": doc.get("cluster_count"),
                    "updated_at": doc.get("updated_at"),
                }
        except:
            pass
        return None


